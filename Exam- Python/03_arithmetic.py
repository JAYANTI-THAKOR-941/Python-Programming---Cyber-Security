num1 = 50
num2 = 2

print("Addition       :", num1 + num2)
print("Subtraction    :", num1 - num2)
print("Multiplication :", num1 * num2)
print("Division       :", num1 / num2)
print("Floor Division :", num1 // num2)
print("Remainder      :", num1 % num2)
print("Power          :", num1 ** num2)

# Output:
# Addition       : 52
# Subtraction    : 48
# Multiplication : 100
# Division       : 25.0
# Floor Division : 25
# Remainder      : 0
# Power          : 2500
